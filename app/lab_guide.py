RANGE = re.compile(r"^\s*(\d+(?:\.\d+)?)\s*[-–]\s*(\d+(?:\.\d+)?)\s*$")
NUMBER = re.compile(r"^\s*[<>]?\s*(\d+(?:\.\d+)?)")


def entry(name):
    n = (name or "").strip().lower()
    return next((g for g in GUIDE if re.search(g["keys"], n)), None)


def _distance(result, reference):
    """How far outside the printed range, as a share of the range's width. None if not plain numbers."""
    rng, val = RANGE.match(reference or ""), NUMBER.match(result or "")
    if not rng or not val:
        return None
    low, high, value = float(rng[1]), float(rng[2]), float(val[1])
    if high <= low:
        return None
    return max(low - value, value - high, 0) / (high - low)


def _degree(distance):
    if distance is None:
        return ""
    return "slightly " if distance < 0.25 else "well " if distance > 1 else ""


def explain(rows):
    """Plain-language summary of a reviewed report, from the lab's own flags and the fixed guide above."""
    flagged = [r for r in rows if r.get("flag") in ("Low", "High")]
    cards = []
    for r in flagged:
        g, direction = entry(r.get("name")), r["flag"].lower()
        dist = _distance(r.get("result"), r.get("reference"))
        degree = _degree(dist)
        if g:
            linked, level, steps = g[direction]
            if dist is not None and dist > 1:
                level = SOON
            cards.append(dict(name=r.get("name", ""), title=g["title"], result=r.get("result", ""), flag=r["flag"],
                              status=f"{degree}{'below' if direction == 'low' else 'above'} the lab's range",
                              what=g["what"], linked=linked, level=level, when=LEVELS[level], steps=steps, source=g["url"]))
        else:
            cards.append(dict(name=r.get("name", ""), title=r.get("name", ""), result=r.get("result", ""), flag=r["flag"],
                              status=f"{degree}{'below' if direction == 'low' else 'above'} the lab's range",
                              what="We don't have a plain-language guide for this test yet.", linked="", level=SOON,
                              when=LEVELS[SOON], steps=["Ask your clinician what this result means for you."], source=ML))
    others = []
    for r in rows:
        if r in flagged:
            continue
        g = entry(r.get("name"))
        others.append(dict(name=r.get("name", ""), what=g["what"] if g else "", source=g["url"] if g else ""))
    total, n = len(rows), len(flagged)
    if not n:
        headline = (f"All {total} results are within the ranges printed on your report. That is reassuring, "
                    "but only your clinician can say what they mean for you, especially if you feel unwell.")
        level = ROUTINE
    else:
        parts = [f"{c['title']} is {c['status']}" for c in cards]
        level = SOON if any(c["level"] == SOON for c in cards) else ROUTINE
        headline = (f"{total - n} of {total} results are within the report's ranges. "
                    f"{n} {'is' if n == 1 else 'are'} outside: " + "; ".join(parts) + ".")
    return dict(headline=headline, level=level, next_step=LEVELS[level], cards=cards, others=others,
                red_flags=RED_FLAGS, general=GENERAL)
